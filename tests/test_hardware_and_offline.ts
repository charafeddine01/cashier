import { HardwareService } from '../src/services/hardwareService';

console.log('=== TEST 1: Supermarket Scale Barcode Parser (Prefixes 20-29) ===');

// Standard EAN-13 Check Digit Calculation helper:
// Weights: odd positions * 1, even positions * 3 (1-based: 1, 3, 5, 7, 9, 11 are * 1; 2, 4, 6, 8, 10, 12 are * 3)
function calculateEan13CheckDigit(code12: string): number {
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    const digit = parseInt(code12[i], 10);
    sum += i % 2 === 0 ? digit : digit * 3;
  }
  const mod = sum % 10;
  return mod === 0 ? 0 : 10 - mod;
}

// 1. Create a scale barcode with prefix 21, PLU 00101, weight 01500 (1.500 kg)
const code12_wt = '21' + '00101' + '01500';
const checkDigit_wt = calculateEan13CheckDigit(code12_wt);
const validWeightBarcode = code12_wt + checkDigit_wt;
console.log('Testing Valid Weight Scale Barcode:', validWeightBarcode);

const parsedWeight = HardwareService.parseScaleBarcode(validWeightBarcode, '21');
console.log('Result:', JSON.stringify(parsedWeight, null, 2));

if (
  parsedWeight.isValid &&
  parsedWeight.isScaleBarcode &&
  parsedWeight.prefix === '21' &&
  parsedWeight.plu === '00101' &&
  parsedWeight.isWeightEmbedded &&
  Math.abs(parsedWeight.weightKg - 1.5) < 0.0001 &&
  parsedWeight.checkDigitValid
) {
  console.log('✅ TEST 1A PASSED: Valid weight-embedded scale barcode parsed correctly.');
} else {
  console.error('❌ TEST 1A FAILED!');
  process.exit(1);
}

// 2. Test Invalid Checksum
const invalidChecksumBarcode = code12_wt + ((checkDigit_wt + 1) % 10);
console.log('\nTesting Invalid Checksum Barcode:', invalidChecksumBarcode);
const parsedInvalid = HardwareService.parseScaleBarcode(invalidChecksumBarcode, '21');
console.log('Result checkDigitValid:', parsedInvalid.checkDigitValid, 'isValid:', parsedInvalid.isValid);

if (!parsedInvalid.checkDigitValid && !parsedInvalid.isValid) {
  console.log('✅ TEST 1B PASSED: Invalid check digit correctly rejected.');
} else {
  console.error('❌ TEST 1B FAILED!');
  process.exit(1);
}

// 3. Test Scale barcode with prefix 20 (Price Embedded: e.g. PLU 00200, Price 00999 -> $9.99)
const code12_pr = '20' + '00200' + '00999';
const checkDigit_pr = calculateEan13CheckDigit(code12_pr);
const validPriceBarcode = code12_pr + checkDigit_pr;
console.log('\nTesting Price Embedded Scale Barcode:', validPriceBarcode);
const parsedPrice = HardwareService.parseScaleBarcode(validPriceBarcode, '21');
console.log('Result isPriceEmbedded:', parsedPrice.isPriceEmbedded, 'embeddedPrice:', parsedPrice.embeddedPrice);

if (parsedPrice.isValid && parsedPrice.isPriceEmbedded && Math.abs(parsedPrice.embeddedPrice - 9.99) < 0.001) {
  console.log('✅ TEST 1C PASSED: Price-embedded scale barcode parsed correctly.');
} else {
  console.error('❌ TEST 1C FAILED!');
  process.exit(1);
}

// 4. Test non-scale product barcode
const nonScaleBarcode = '8901234567890';
const parsedNonScale = HardwareService.parseScaleBarcode(nonScaleBarcode, '21');
if (!parsedNonScale.isScaleBarcode) {
  console.log('✅ TEST 1D PASSED: Non-scale barcode correctly distinguished.');
} else {
  console.error('❌ TEST 1D FAILED!');
  process.exit(1);
}

console.log('\n=== TEST 2: Thermal Printer ESC/POS Byte Generation ===');
const receiptBytes = HardwareService.generateEscPosReceipt({
  companyName: 'OmniPOS SuperStore',
  invoiceNumber: 'INV-2026-0001',
  dateStr: '2026-10-25 12:00:00',
  cashierName: 'Cashier 1',
  items: [
    { name: 'Organic Bananas', qty: 1.5, price: 1.99, total: 2.99 },
    { name: 'Whole Milk 1L', qty: 2, price: 3.50, total: 7.00 },
  ],
  subtotal: 9.99,
  tax: 0.50,
  discount: 0,
  grandTotal: 10.49,
  paidCash: 20.00,
  changeGiven: 9.51,
  footerText: 'Thank you for your visit!',
  paperWidth: '80mm',
  kickDrawer: true,
  cutPaper: true,
});

console.log('Total ESC/POS Generated Bytes:', receiptBytes.length);

// Verify Cash Drawer Kick Sequence: \x1B\x70\x00\x19\xFA
const kickFound = receiptBytes.some((_, i, arr) => {
  return (
    arr[i] === 0x1b &&
    arr[i + 1] === 0x70 &&
    arr[i + 2] === 0x00 &&
    arr[i + 3] === 0x19 &&
    arr[i + 4] === 0xfa
  );
});

// Verify Paper Cut Sequence: \x1D\x56\x42\x00
const cutFound = receiptBytes.some((_, i, arr) => {
  return (
    arr[i] === 0x1d &&
    arr[i + 1] === 0x56 &&
    arr[i + 2] === 0x42 &&
    arr[i + 3] === 0x00
  );
});

console.log('Cash Drawer Kick byte pattern found:', kickFound);
console.log('Paper Cut byte pattern found:', cutFound);

if (kickFound && cutFound && receiptBytes.length > 50) {
  console.log('✅ TEST 2 PASSED: ESC/POS receipt generated with drawer kick and paper cut.');
} else {
  console.error('❌ TEST 2 FAILED!');
  process.exit(1);
}

